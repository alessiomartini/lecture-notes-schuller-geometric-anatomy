"""Create a stub chapter for every lecture that has no chapter file yet, and the \\include list in main.tex.

A stub has the chapter title, the Sources box (video link, length, transcript file) and an empty Reading box,
so the book always lists the whole course. Existing chapter files are never touched.
Run: python -I -X utf8 tools/stubs.py
"""
import csv, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LN = ROOT / 'lecture-notes'
rows = list(csv.DictReader(open(ROOT / 'materials/videos.csv', encoding='utf-8')))


def clean(title):
    t = re.sub(r'\s*-\s*(Lec|lec|L)\s*\d+.*$', '', title)     # drop "- Lec 02 - Frederic Schuller"
    t = re.sub(r'\s*-\s*\d+\s*-\s*Frederic.*$', '', t)
    return t.replace('Conncections', 'Connections').replace('deRham', 'de Rham').strip(' -')


def slug(t):
    return '-'.join(re.sub(r'[^a-z0-9 ]', ' ', t.lower()).split()[:4])


includes = []
for r in rows:
    n, title = int(r['n']), clean(r['title'])
    existing = sorted((LN / 'chapters').glob(f'ch{n:02d}-*.tex'))
    path = existing[0] if existing else LN / f'chapters/ch{n:02d}-{slug(title)}.tex'
    includes.append(f'\\include{{chapters/{path.stem}}}')
    if existing:
        continue
    tex = title.replace('&', '\\&')
    path.write_text(f"""% !TEX root = ../main.tex
% STUB: generated by tools/stubs.py; write the chapter from materials/transcripts/C{n:02d}-V01.txt
\\chapter{{{tex}}}\\label{{ch:l{n:02d}}}
\\begin{{paracol}}{{2}}

\\begin{{sources}}
\\begin{{tabularx}}{{\\linewidth}}{{@{{}}l l L@{{}}}}
\\toprule
\\textbf{{Video}} & \\textbf{{Length}} & \\textbf{{Content}}\\\\
\\midrule
\\seg{{{n}}}{{1}}{{Lecture {n}: {tex}}} & {r['duration']} & (to be written)\\\\
\\bottomrule
\\end{{tabularx}}

\\smallskip
\\textbf{{Transcript}} \\file{{materials/transcripts/C{n:02d}-V01.txt}}.
\\end{{sources}}

\\begin{{reading}}[Where this lecture sits in the other notes]
(to be written)
\\end{{reading}}

\\emph{{This chapter has not been written yet.}}

\\flushside
\\end{{paracol}}
""", encoding='utf-8')
    print('stub', path.name)

main = (LN / 'main.tex').read_text(encoding='utf-8')
block = '% BEGIN CHAPTERS (tools/stubs.py)\n' + '\n'.join(includes) + '\n% END CHAPTERS'
if '% BEGIN CHAPTERS' in main:
    main = re.sub(r'% BEGIN CHAPTERS.*?% END CHAPTERS', lambda m: block, main, flags=re.S)
else:
    main = main.replace('\\include{chapters/ch01-logic}', block)
(LN / 'main.tex').write_text(main, encoding='utf-8')
print(len(includes), 'chapters in main.tex')
