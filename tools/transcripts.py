"""Build the per-lecture transcripts and the video table.

Inputs:
  materials/videos.csv                          n, kind, youtube, fautv, title, duration, lecturer (from SOURCES inventory)
  materials/transcripts/raw/NNN-<id>.en-orig.json3   YouTube auto-captions, or
  materials/transcripts/raw/NNN-<id>.whisper.txt     local faster-whisper output ('seconds<TAB>text')
Outputs:
  materials/transcripts/CXX-V01.txt             one line per ~20 s, '[m:ss] text' (C = lecture number)
  lecture-notes/videos.tex                      \\tsvideo{C@1}{id} table read by the preamble (\\ts links)
Run: python -I -X utf8 tools/transcripts.py
"""
import csv, json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAT = ROOT / 'materials'
LINE_SECONDS = 20
# own downloads first, then the shared download of the inventory repo (lecture-notes-schuller-courses)
RAWS = [MAT / 'transcripts/raw', ROOT.parent / 'lecture-notes-schuller-courses/materials/raw/C1']


def mmss(s):
    s = int(s)
    return f'{s // 3600}:{s // 60 % 60:02d}:{s % 60:02d}' if s >= 3600 else f'{s // 60}:{s % 60:02d}'


def words_json3(path):
    for ev in json.load(open(path, encoding='utf-8')).get('events', []):
        for seg in ev.get('segs', []):
            w = seg['utf8'].strip()
            if w:
                yield (ev['tStartMs'] + seg.get('tOffsetMs', 0)) / 1000, w


def words_whisper(path):
    for line in open(path, encoding='utf-8'):
        t, _, text = line.rstrip('\n').partition('\t')
        yield float(t), text


def lines(words):
    out, start, buf = [], None, []
    for t, w in words:
        start = t if start is None else start
        buf.append(w)
        if t - start >= LINE_SECONDS:
            out.append((start, ' '.join(buf)))
            start, buf = None, []
    if buf:
        out.append((start, ' '.join(buf)))
    return out


rows = list(csv.DictReader(open(MAT / 'videos.csv', encoding='utf-8')))
with open(ROOT / 'lecture-notes/videos.tex', 'w', encoding='utf-8') as f:
    f.write('% Generated by tools/transcripts.py: YouTube ID of every lecture (lecture@1)\n')
    for r in rows:
        f.write(f"\\tsvideo{{{r['n']}@1}}{{{r['youtube']}}} % {r['title']}\n")

done = []
for r in rows:
    n, vid = int(r['n']), r['youtube']
    src = words = None
    for raw in RAWS:
        src = next(iter(sorted(raw.glob(f'{n:03d}-{vid}.en-orig.json3'))), None)
        if src:
            words = words_json3(src)
            break
        src = next(iter(raw.glob(f'{n:03d}-{vid}.whisper.txt')), None)
        if src:
            words = words_whisper(src)
            break
    if not src:
        continue
    out = MAT / f'transcripts/C{n:02d}-V01.txt'
    with open(out, 'w', encoding='utf-8') as f:
        f.write(f"Lecture {n}: {r['title']} | https://youtu.be/{vid} | {r['duration']} | source: {src.name}\n")
        for t, text in lines(words):
            f.write(f'[{mmss(t)}] {text}\n')
    done.append(n)
print(f'{len(rows)} lectures, transcripts for {done}')
